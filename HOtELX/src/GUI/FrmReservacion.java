    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
    
        String cliente      = txtCliente.getText();
String fechaReserva = txtFechaReserva.getText();
int cantidadDias    = Integer.parseInt(txtCantidadDias.getText());
String tipoCuarto   = cboTipoCuarto.getSelectedItem().toString();

Reservacion reservacion = new Reservacion();
reservacion.setCliente(cliente);
reservacion.setFechaReserva(fechaReserva);
reservacion.setCantidadDias(cantidadDias);
reservacion.setTipoCuarto(tipoCuarto);

reservacionservice.agregar(reservacion);
JOptionPane.showMessageDialog(this, "Reservacion guardada correctamente.");
 
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
mdlReservaciones.setRowCount(0);

for (Reservacion r : reservacionservice.listar()) {
    mdlReservaciones.addRow(new Object[]{
        r.getCliente(),
        r.getTipoCuarto(),
        r.getFechaReserva(),
        r.getCantidadDias(),
        r.getPrecio(),
        r.getAumento(),
        r.getTotal()
    });
}
    }//GEN-LAST:event_btnMostrarActionPerformed

